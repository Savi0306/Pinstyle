import React from 'react';
import { ResponsiveContainer, BarChart, Bar, XAxis, YAxis, Tooltip, CartesianGrid, PieChart, Pie, Cell } from 'recharts';

const segmentData = [
  { name: 'Clean Girl', revenue: 13876800, orders: 1960 },
  { name: 'Old Money', revenue: 13009500, orders: 1490 },
  { name: 'Trads', revenue: 11814750, orders: 1310 },
];

const pieData = [
  { name: 'Clean Girl Minimalist', value: 36, color: '#f43f5e' },
  { name: 'Old Money Prep', value: 33, color: '#3b82f6' },
  { name: 'Trads (Heritage)', value: 31, color: '#10b981' },
];

export default function ChartSection({ selectedSegment }) {
  const filteredData = selectedSegment === 'All' 
    ? segmentData 
    : segmentData.filter(d => d.name.toLowerCase().includes(selectedSegment.toLowerCase()));

  return (
    <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
      <div className="lg:col-span-2 bg-slate-900/60 border border-slate-800/80 rounded-2xl p-6">
        <h3 className="text-base font-semibold text-white mb-1">Segment Revenue Comparison (INR ₹)</h3>
        <p className="text-xs text-slate-400 mb-6">Net monthly revenue generated by each targeted launch aesthetic</p>
        <div className="h-64">
          <ResponsiveContainer width="100%" height="100%">
            <BarChart data={filteredData}>
              <CartesianGrid strokeDasharray="3 3" stroke="#1e293b" />
              <XAxis dataKey="name" stroke="#64748b" fontSize={12} />
              <YAxis stroke="#64748b" fontSize={12} tickFormatter={(val) => `₹${(val/100000).toFixed(1)}L`} />
              <Tooltip 
                contentStyle={{ backgroundColor: '#0f172a', borderColor: '#334155', color: '#fff' }} 
                formatter={(value) => [`₹${value.toLocaleString('en-IN')}`, 'Net Revenue']}
              />
              <Bar dataKey="revenue" fill="#f43f5e" radius={[6, 6, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        </div>
      </div>

      <div className="bg-slate-900/60 border border-slate-800/80 rounded-2xl p-6">
        <h3 className="text-base font-semibold text-white mb-1">Aesthetic Revenue Share</h3>
        <p className="text-xs text-slate-400 mb-6">Percentage contribution to total store sales</p>
        <div className="h-48 flex items-center justify-center">
          <ResponsiveContainer width="100%" height="100%">
            <PieChart>
              <Pie data={pieData} cx="50%" cy="50%" innerRadius={50} outerRadius={75} dataKey="value">
                {pieData.map((entry, index) => (
                  <Cell key={`cell-${index}`} fill={entry.color} />
                ))}
              </Pie>
              <Tooltip contentStyle={{ backgroundColor: '#0f172a', borderColor: '#334155', color: '#fff' }} />
            </PieChart>
          </ResponsiveContainer>
        </div>
        <div className="space-y-2 mt-4">
          {pieData.map((item, i) => (
            <div key={i} className="flex items-center justify-between text-xs">
              <div className="flex items-center gap-2">
                <div className="w-2.5 h-2.5 rounded-full" style={{ backgroundColor: item.color }} />
                <span className="text-slate-300">{item.name}</span>
              </div>
              <span className="font-semibold text-white">{item.value}%</span>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
